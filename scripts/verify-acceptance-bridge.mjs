import { spawn } from 'node:child_process';
import { readFileSync, rmSync } from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
const args = process.argv.slice(2);
assert.ok(args.every(arg => /^--(core|ui|result)=/.test(arg)));
const result = args.find(arg => arg.startsWith('--result='))?.slice(9);
assert.ok(result, '--result is required');
const env = Object.fromEntries(['PATH','SystemRoot','TEMP','TMP','APPDATA','LOCALAPPDATA'].flatMap(key => process.env[key] ? [[key,process.env[key]]] : []));
const child = spawn(path.resolve('dist-personal/electron/electron.exe'), [path.resolve('scripts/smoke-acceptance-bridge.mjs'), ...args], { env, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] });
child.stdout.pipe(process.stdout); child.stderr.pipe(process.stderr);
const timer = setTimeout(() => { if (child.pid && child.exitCode === null) spawn('taskkill.exe', ['/PID',String(child.pid),'/T','/F'], { windowsHide: true, stdio: 'ignore' }); }, 45000);
const code = await new Promise(resolve => child.once('close', resolve)); clearTimeout(timer);
const evidence = JSON.parse(readFileSync(path.resolve(result), 'utf8'));
assert.equal(path.dirname(path.resolve(evidence.cleanupRoot)), path.resolve(os.tmpdir()));
assert.ok(path.basename(evidence.cleanupRoot).startsWith('nex-acceptance-electron-'));
rmSync(evidence.cleanupRoot, { recursive: true, force: true, maxRetries: 20, retryDelay: 100 });
assert.equal(code, 0); assert.equal(evidence.passed, true);
